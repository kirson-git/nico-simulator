// Course navigation and packet playback are browser-only; never reset the cluster.
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
try {
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[],writes=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.method()!=='GET')writes.push(r.url());});
 await page.goto('http://127.0.0.1:8780/#modes');
 await page.getByRole('button',{name:'Original PNG animation',exact:true}).click();
 await page.locator('#course-menu > summary').focus();
 await page.keyboard.press('Enter');
 assert.equal(await page.locator('#course-menu').getAttribute('open'),'','Desktop contents remain open after keyboard activation');
 assert.ok(await page.locator('#chapters a').first().isVisible());
 await page.getByRole('button',{name:'Play packet',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#packet-stage')?.textContent.includes('2 / 3'));
 await page.getByRole('button',{name:'Pause packet'}).click();
 const paused=await page.locator('#packet-stage').innerText();
 await page.waitForTimeout(1900);
 assert.equal(await page.locator('#packet-stage').innerText(),paused,'Pause stops progression');
 await page.getByRole('button',{name:'Next packet step'}).click();
 assert.match(await page.locator('#packet-stage').innerText(),/3 \/ 3/);
 await page.getByRole('button',{name:'Replay packet'}).click();
 assert.match(await page.locator('#packet-stage').innerText(),/1 \/ 3/);
 await page.getByRole('checkbox',{name:'Show configured HBN example'}).check();
 await page.getByRole('button',{name:'Next packet step'}).click();
 assert.match(await page.locator('#packet-caption').innerText(),/VXLAN/);
 await page.getByRole('button',{name:'NIC mode',exact:true}).click();
 assert.match(await page.locator('#packet-stage').innerText(),/1 \/ 3/);
 assert.doesNotMatch(await page.locator('#packet-caption').innerText(),/VXLAN/);
 await page.getByRole('button',{name:'Play packet',exact:true}).click();
 await page.locator('#chapters a').first().click();
 await page.waitForTimeout(1900);
 assert.equal(await page.locator('#packet-stage').count(),0,'Leaving the lesson disposes playback');
 await page.goBack();
 await page.getByRole('button',{name:'Original PNG animation',exact:true}).click();
 await page.getByRole('button',{name:'Play packet',exact:true}).waitFor();
 await page.reload();
 await page.getByRole('button',{name:'Original PNG animation',exact:true}).click();
 await page.getByRole('button',{name:'Play packet',exact:true}).waitFor();
 const nav = await page.locator('[data-course-nav]').innerText();
 for(const name of ['DPU 101','Kubernetes basics','Prerequisites','DPF operator','DPU discovery','Europe & Asia','DPU provisioning','Host Ubuntu','HBN networking','Validation & troubleshooting'])assert.ok(nav.includes(name),name);
 const side=await page.locator('.course-sidebar').boundingBox();
 await page.locator('main').evaluate(el=>el.scrollTop=el.scrollHeight);
 assert.equal((await page.locator('.course-sidebar').boundingBox()).x,side.x);
 await page.screenshot({path:'/test/course-modes.png',fullPage:true});
 await page.locator('[data-course-nav] a[href="/host-ubuntu"]').click();
 assert.equal(await page.locator('[data-course-nav] a[aria-current="page"]').getAttribute('href'),'/host-ubuntu');
 await page.locator('[data-course-nav] a[href="/kubernetes"]').click();
 await page.waitForFunction(()=>document.querySelector('#connection')?.textContent.includes('Connected'));
 assert.equal(await page.locator('[data-course-nav] a[aria-current="page"]').getAttribute('href'),'/kubernetes');
 await page.screenshot({path:'/test/course-kubernetes.png'});
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:8780/#modes');
 await page.getByRole('button',{name:'Original PNG animation',exact:true}).click();
 await page.locator('#course-menu > summary').click();
 await page.locator('#chapters a[href="/#modes"]').click();
 assert.equal(await page.locator('#course-menu').getAttribute('open'),null);
 assert.equal(await page.evaluate(()=>document.activeElement === document.querySelector('#course-menu > summary')),true,'Same-chapter menu selection retains visible focus');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.getByRole('button',{name:'Next packet step'}).click();
 assert.match(await page.locator('#packet-stage').innerText(),/2 \/ 3/);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'/test/course-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 assert.deepEqual(writes,[]);
 console.log('PASS: deep links, Back/reload, full course sidebar across lessons, packet play/pause/step/replay, mode reset, timer disposal, reduced motion and mobile layout.');
} finally {await browser.close();}
