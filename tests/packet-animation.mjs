import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8780/#modes');
 await page.getByRole('button',{name:'Original PNG animation',exact:true}).click();
 const photo=await page.locator('#mode-photo').boundingBox();
 const play=await page.locator('#packet-play').boundingBox();
 assert.ok(play.x>photo.x+photo.width/2 && play.y<photo.y+60,'Play is inside the image at top right');
 assert.equal(await page.locator('#hbn-example').isChecked(),true);
 await page.getByRole('button',{name:'Play packet',exact:true}).click();
 await page.waitForTimeout(1300);
 const position=()=>page.locator('#packet-track').evaluate(el=>[el.style.getPropertyValue('--packet-x'),el.style.getPropertyValue('--packet-y')]);
 assert.notEqual((await position())[1],'17%','Packet moves before reaching the next stage');
 await page.getByRole('button',{name:'Pause packet',exact:true}).click();
 const paused=await position();await page.waitForTimeout(400);assert.deepEqual(await position(),paused);
 await page.getByRole('button',{name:'Play packet',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('#packet-wrapper').hidden);
 assert.match(await page.locator('#packet-wrapper').innerText(),/VXLAN/);
 await page.getByRole('button',{name:'Pause packet',exact:true}).click();
 await page.screenshot({path:'/test/packet-vxlan.png',fullPage:true});
 await page.getByRole('button',{name:'NIC mode',exact:true}).click();
 assert.equal(await page.locator('#hbn-example').isChecked(),false);
 assert.equal(await page.locator('#packet-wrapper').isVisible(),false);
 await page.getByRole('button',{name:'DPU mode',exact:true}).click();
 assert.equal(await page.locator('#hbn-example').isChecked(),true);
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.getByRole('button',{name:'Next packet step'}).click();
 assert.deepEqual(await position(),['59%','72%']);
 await page.setViewportSize({width:390,height:844});
 const left=await page.locator('.photo-mode-controls').boundingBox();
 const right=await page.locator('.photo-playback').boundingBox();
 assert.ok(left.x+left.width<=right.x,'Mode and playback controls do not overlap on mobile');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'/test/packet-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: top-right controls, path motion, precise pause/resume, default DPU VXLAN, NIC reset, reduced motion and mobile toolbar.');
} finally {await browser.close();}
